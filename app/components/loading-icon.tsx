export default function Loader({
  size = 64,
  duration = 1.2,
  darkColor = "#000000",
  lightColor = "#888787",
  label = "Loading",
  className,
}: LoaderProps) {
  const style = {
    "--loader-dark": darkColor,
    "--loader-light": lightColor,
    "--loader-duration": `${duration}s`,
  } as CSSProperties;

  return (
    <svg
      role="status"
      aria-label={label}
      width={size}
      height={(size * 93) / 94}
      viewBox="0 0 94 93"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      className={["loader-svg", className].filter(Boolean).join(" ")}
      style={style}
    >
      {RAYS.map((ray, i) => (
        <path
          key={i}
          d={ray.d}
          className="loader-ray"
          style={{
            fill: `var(--loader-${ray.tone})`,
            // Negative delay so the animation is already mid-cycle on mount
            animationDelay: `${-(duration - (i * duration) / RAYS.length)}s`,
          }}
        />
      ))}

      <style>{`
        .loader-ray {
          animation: loader-fade var(--loader-duration) linear infinite;
        }
        @keyframes loader-fade {
          0%   { opacity: 1; }
          100% { opacity: 0.12; }
        }
        @media (prefers-reduced-motion: reduce) {
          .loader-ray { animation-duration: 3s; }
        }
      `}</style>
    </svg>
  );
}